# ================================================================
# Legend, README and claim-trace text for the behavior main figure
# MMMSociability
# ================================================================
# Text only. Mirrors the role of Functions/gamm_manuscript_docs.R for the
# behavior figure, but every scientific number is PASSED IN rather than written
# as a literal, so a legend can never drift away from the table it describes.
# `facts` is the single list the assembler builds from the canonical tables; if a
# required entry is absent the writer fails rather than emitting a plausible
# sentence.
# ================================================================

.bmf_need <- function(facts, keys) {
  missing <- keys[!keys %in% names(facts)]
  if (length(missing) > 0L) {
    stop("behavior_main_figure_docs.R: missing required fact(s): ",
         paste(missing, collapse = ", "), call. = FALSE)
  }
  invisible(TRUE)
}

#' Draft figure legend for the behavior main figure.
#'
#' Deliberately states the temporal order first: the single most common
#' misreading of this figure would be to treat the CON/RES/SUS labels as if they
#' had been known when the RFID measurement was taken.
bmf_write_legend_draft <- function(path, facts) {
  .bmf_need(facts, c(
    "n_total", "n_female", "n_male", "group_counts", "combz_components_plain",
    "window_definition", "n_complete_window", "movement_unit",
    "assoc_rho", "assoc_ci", "assoc_q", "pred_r2", "pred_perm_p",
    "pred_n_perm", "pred_null_median", "pred_null_interval",
    "pred_repeated_r2", "pred_repeated_interval", "pred_interval_type",
    "pred_baseline_r2", "cv_scheme", "validation_scheme",
    "panel_a_domains", "pred_n_null_draws", "combz_parity_max_diff",
    "combz_thresholds", "combz_n_components"))

  gc <- facts$group_counts
  lines <- c(
    "# Behavior main figure - legend draft",
    "",
    paste("Generated by `Analysis/27_build_behavior_main_figure.R`.",
          "Four panels. Semantic filenames only; the manuscript figure number",
          "is assigned during whole-manuscript assembly."),
    "",
    "---",
    "",
    "## Full legend (draft)",
    "",
    paste0(
      "**Early home-cage locomotor activity carries continuous, internal ",
      "out-of-sample information about the later composite stress-burden ",
      "score.** Throughout, RFID home-cage measurement PRECEDES the endpoint ",
      "battery: the CON/RES/SUS labels are derived from the later outcome and ",
      "did not exist at the time of the RFID recording, so they are referred ",
      "to as the later outcome group."),
    "",
    paste0(
      "**(a) Experimental design and later outcome.** Chronology, left to ",
      "right: adolescent social instability stress; continuous RFID home-cage ",
      "monitoring across four repeated regroupings (CC1-CC4), from which the ",
      "analysed first-night window and the behavioural domain inventory are ",
      "extracted; then the later behavioural and physiological battery, from ",
      "which the outcome is constructed. Analysed window: ",
      facts$window_definition, ". The listed behavioural domains (",
      paste(gsub("\n", " ", facts$panel_a_domains), collapse = "; "),
      ") are what the continuous record CHARACTERISES; none is presented as a ",
      "group difference, the latent-state and inactivity rows are measurement ",
      "descriptions only, and proximity-based measures are described as ",
      "social-spatial or co-location organization rather than as sociability. ",
      "The later composite stress-burden score (CombZ) is the unweighted mean ",
      "of ", facts$combz_n_components, " standardized, direction-aligned ",
      "components (", paste(facts$combz_components_plain, collapse = ", "),
      "), so it is behavioural *and* physiological. LOWER CombZ = GREATER ",
      "later stress burden. Susceptibility is then assigned within sex among ",
      "stress-exposed animals (thresholds ", facts$combz_thresholds,
      "), i.e. strictly after the later measurement. The repository reproduces ",
      "canonical CombZ and the later outcome assignments exactly from the ",
      "historically defined component z-scores (max |dCombZ| = ",
      facts$combz_parity_max_diff, ", 0 of 93 label mismatches); the ",
      "historical upstream standardization is preserved as source provenance ",
      "rather than redefined. n = ", facts$n_total, " animals (", gc[["CON"]],
      " CON, ", gc[["RES"]], " RES, ", gc[["SUS"]], " SUS; ", facts$n_female,
      " female, ", facts$n_male, " male)."),
    "",
    paste0(
      "**(b) First-night Movement**, grouped by later outcome classification. ",
      "Window: ", facts$window_definition, ". Movement is ",
      facts$movement_unit, ". One point = one animal; all animals are shown; ",
      "the bar is the interquartile range and the tick the median of the ",
      "plotted values. NO categorical contrast is annotated: the declared ",
      "canonical categorical test on this window is null in both sexes, and ",
      "the one nominally supported pooled-sex contrast is recorded upstream as ",
      "descriptive and non-claimable. The panel's role is to show the ",
      "distribution of the variable analysed in (c) and (d). Window coverage ",
      "is not complete for every animal: ", facts$n_complete_window, " of ",
      facts$n_total, " have all expected slots, the remainder are missing ",
      "leading slots only, and there are no interior or trailing gaps."),
    "",
    paste0(
      "**(c) Early Movement and later CombZ.** One point = one animal, pooled ",
      "across sex, with the later outcome group carried redundantly by point ",
      "shape and fill so the panel survives greyscale; sex is not encoded. ",
      "The association is a single POOLED Spearman rank correlation with ",
      "a bootstrap confidence interval: rho = ", facts$assoc_rho,
      ", 95% CI ", facts$assoc_ci, ", Benjamini-Hochberg q = ", facts$assoc_q,
      " within the three-feature a priori family, n = ", facts$n_total,
      ". Group colour is a visual aid only; three separate within-group ",
      "correlations are NOT implied or reported. Because the canonical model is ",
      "rank-based, no fitted line is drawn: an ordinary least-squares line ",
      "would not be the canonical model, and the descriptive quantile-median ",
      "guide is non-monotone in this sample. Pooling is appropriate because the ",
      "formal feature-by-sex interaction is null for all three a priori ",
      "features; sex-stratified views are descriptive candidates only. The ",
      "negative sign means greater early Movement goes with lower CombZ, i.e. ",
      "greater later stress burden."),
    "",
    paste0(
      "**(d) Out-of-sample prediction of later CombZ.** Left, observed later ",
      "CombZ against leave-one-animal-out predicted CombZ; each point is one ",
      "held-out animal, predicted by a model refitted without that animal, and ",
      "the dashed line is the identity y = x, shown as a visual reference only ",
      "(no regression is fitted to it and none is reported). Right, the actual ",
      "distribution of ", facts$pred_n_null_draws, " permutation ",
      "cross-validation R-squared values, with the null median dashed and the ",
      "observed value marked; every draw was produced by reshuffling the ",
      "outcome and re-running the entire leave-one-animal-out loop, so the ",
      "null is the real refit distribution and not a density reconstructed ",
      "from summary quantiles. Performance is the canonical cross-validated ",
      "R-squared = ", facts$pred_r2, "; reference ", facts$pred_n_perm,
      "; permutation p = ", facts$pred_perm_p, ". Null median ",
      facts$pred_null_median, ", 2.5-97.5% ", facts$pred_null_interval,
      "; intercept-only baseline ", facts$pred_baseline_r2,
      ". The repeated cross-validation companion (", facts$pred_repeated_r2,
      " ", facts$pred_repeated_interval, ") is a ", facts$pred_interval_type,
      ", i.e. a split-to-split resampling interval and NOT a bootstrap ",
      "confidence interval. This is INTERNAL out-of-sample validation within a ",
      "single cohort: first-night Movement contained internal out-of-sample ",
      "information about later CombZ. It is not external validation, not an ",
      "independent cohort, and an R-squared of this magnitude is informative ",
      "rather than accurate prediction. No causal claim is made."),
    "",
    "---",
    "",
    "## Wording that must not be changed",
    "",
    paste0("- The cross-validation grouping unit is the **animal**. Cage, ",
           "social group and batch are not grouping units; do not imply ",
           "cage- or batch-level generalisation."),
    paste0("- 'Internal out-of-sample validation.' Never 'external ",
           "validation', 'independent cohort' or 'independently validated'. ",
           "The endpoint is continuous CombZ, so never report an AUC or ",
           "describe this as classification."),
    paste0("- The repeated-CV interval is a split-to-split resampling ",
           "interval. Do not call it a bootstrap or a confidence interval."),
    paste0("- The permutation null in (d) is the ACTUAL set of ",
           facts$pred_n_null_draws, " refit statistics persisted by the ",
           "producing stage. It must never be replaced by a density ",
           "reconstructed from published quantiles."),
    paste0("- **LOWER CombZ = greater later stress burden.** Do not describe ",
           "CombZ as a burden score without inverting the sign."),
    paste0("- Panel (a) is a design and definition schematic. Its domain ",
           "inventory states what is measured; it asserts no group difference ",
           "and must not be described as a multi-domain signature."),
    paste0("- Panel (b) is descriptive. Do not add stars, brackets, or q ",
           "values to it."),
    paste0("- Panel (c) reports ONE pooled correlation. Do not describe the ",
           "group colours as three correlations."),
    paste0("- CombZ provenance: canonical CombZ and outcome assignments are ",
           "reproduced exactly from the historically defined component ",
           "z-scores. Do not claim CombZ is fully regenerated from raw ",
           "behavioural and physiological data."),
    paste0("- Movement RMSSD is a supporting association only and must not be ",
           "described as an independent predictor. Entropy persistence (ACF1) ",
           "is not FDR-supported at the primary resolution and must carry ",
           "qualified wording."),
    "",
    "## Methods pointers",
    "",
    paste0("Panels (b)-(d) share one window and one animal set. Full ",
           "statistics are in `tables/manuscript/behavior_main_key_results.csv`; ",
           "per-panel plotted values are in `source_data/`; provenance is in ",
           "`manifests/`; claim-to-analysis mapping is in ",
           "`audit/behavior_main_claim_trace.csv`. Domain-contrast heatmaps, ",
           "the longitudinal movement characterisation, and the GAMM temporal ",
           "analyses are Extended Data."))
  writeLines(lines, path)
  invisible(path)
}


#' Co-author facing README for the Stage 27 output tree.
