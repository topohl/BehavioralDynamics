# ================================================================
# Legend, README and claim-trace text for the behavior main figure
# MMMSociability
# ================================================================
# Text only. Mirrors the role of Functions/gamm_manuscript_docs.R for the
# behavior figure, but every scientific number is PASSED IN rather than written
# as a literal, so a legend can never drift away from the table it describes.
# `facts` is the single list the assembler builds from the canonical tables; if a
# required entry is absent the writer fails rather than emitting a plausible
# sentence.
# ================================================================

.bmf_need <- function(facts, keys) {
  missing <- keys[!keys %in% names(facts)]
  if (length(missing) > 0L) {
    stop("behavior_main_figure_docs.R: missing required fact(s): ",
         paste(missing, collapse = ", "), call. = FALSE)
  }
  invisible(TRUE)
}

#' Draft figure legend for the behavior main figure.
#'
#' Deliberately states the temporal order first: the single most common
#' misreading of this figure would be to treat the CON/RES/SUS labels as if they
#' had been known when the RFID measurement was taken.
bmf_write_legend_draft <- function(path, facts) {
  .bmf_need(facts, c(
    "n_total", "n_female", "n_male", "group_counts", "combz_components_plain",
    "window_definition", "n_complete_window", "movement_unit",
    "assoc_rho", "assoc_ci", "assoc_q", "pred_r2", "pred_perm_p",
    "pred_n_perm", "pred_null_median", "pred_null_interval",
    "pred_repeated_r2", "pred_repeated_interval", "pred_interval_type",
    "pred_baseline_r2", "cv_scheme", "validation_scheme",
    "domain_family", "domain_supported", "domain_n_cells"))

  gc <- facts$group_counts
  lines <- c(
    "# Behavior main figure - legend draft",
    "",
    paste("Generated by `Analysis/27_build_behavior_main_figure.R`.",
          "Semantic filenames only; the manuscript figure number is assigned",
          "during whole-manuscript assembly."),
    "",
    "---",
    "",
    "## Full legend (draft)",
    "",
    paste0(
      "**Early home-cage locomotor responsivity carries continuous, ",
      "out-of-sample information about the later behavioural outcome.** ",
      "Throughout, RFID home-cage measurement PRECEDES the endpoint battery: ",
      "the CON/RES/SUS labels are derived from the later outcome and were not ",
      "known at the time of the RFID recording, so they are referred to as the ",
      "later outcome group."),
    "",
    paste0(
      "**(a)** Study and outcome schematic. CombZ, the later behavioural ",
      "outcome, is the unweighted arithmetic mean of ", length(facts$combz_components),
      " component z-scores (", paste(facts$combz_components_plain, collapse = ", "),
      "); the composite is therefore behavioural *and* physiological. Higher ",
      "CombZ indicates a more resilient-like endpoint and lower CombZ a worse ",
      "depressive-like endpoint; the direction is not harmonised to ",
      "'higher = worse'. The component z-scoring reference and the RES/SUS ",
      "threshold are defined in an upstream endpoint workbook rather than in ",
      "the analysis code, and are labelled as external in the panel. Right, ",
      "distribution of CombZ per later outcome group within sex; points are ",
      "animals, the bar is the interquartile range and the tick the median. ",
      "n = ", facts$n_total, " animals (", gc[["CON"]], " CON, ", gc[["RES"]],
      " RES, ", gc[["SUS"]], " SUS; ", facts$n_female, " female, ",
      facts$n_male, " male)."),
    "",
    paste0(
      "**(b)** Domain-level behavioural characterisation during the first ",
      "active phase. Fill encodes the standardized group contrast (Hedges g) ",
      "and encodes effect direction and magnitude only - never significance. ",
      "Cells outlined in black are the ", facts$domain_supported, " of ",
      facts$domain_n_cells, " that pass the declared Benjamini-Hochberg family ",
      "(", facts$domain_family, "). Contrasts are estimated within sex from a ",
      "linear model of the per-animal domain score on later outcome group and ",
      "sex, with per-domain scores built under a strict-completeness rule. ",
      "This panel shows the breadth of the characterisation; it is not evidence ",
      "of a multi-domain signature, and it is confined to the first active ",
      "phase rather than the longitudinal record."),
    "",
    paste0(
      "**(c)** Animal-level locomotor activity during the first active phase, ",
      "by later outcome group and sex. Window: ", facts$window_definition,
      ". Movement is ", facts$movement_unit, ". Each point is one animal, all ",
      "animals are shown; the bar is the interquartile range and the tick the ",
      "median of the plotted values. No categorical group contrast is ",
      "annotated: the repository's declared canonical categorical test on this ",
      "window is null in both sexes, and the one nominally supported ",
      "pooled-sex contrast is recorded as descriptive and not claimable. The ",
      "panel's role is to show the distribution underlying the early signal. ",
      "Window coverage is not complete for every animal: ",
      facts$n_complete_window, " of ", facts$n_total,
      " animals have all expected slots, the remainder are missing leading ",
      "slots only, and there are no interior or trailing gaps."),
    "",
    paste0(
      "**(d)** Early locomotor activity versus the later outcome, one point ",
      "per animal, pooled across sex with sex carried by point shape. The ",
      "canonical association is a Spearman rank correlation with a ",
      "bootstrap confidence interval: rho = ", facts$assoc_rho, ", 95% CI ",
      facts$assoc_ci, ", Benjamini-Hochberg q = ", facts$assoc_q, " within the ",
      "three-feature a priori family, n = ", facts$n_total, ". Because the ",
      "inferential model is rank-based, no least-squares line is drawn; the ",
      "dashed line joins the median outcome within five equal-count bins of ",
      "the predictor and is descriptive only. The analysis is pooled because ",
      "the formal feature-by-sex interaction is null for all three a priori ",
      "features; sex-stratified estimates are descriptive and are not ",
      "interaction tests. The negative sign means higher early locomotor ",
      "activity is associated with a worse later outcome."),
    "",
    paste0(
      "**(e)** Out-of-sample prediction of the later outcome from early ",
      "behaviour. Left, observed versus held-out predicted CombZ; the ",
      "validation scheme is ", facts$validation_scheme, ", so every predicted ",
      "value was produced by a model refitted without that animal, and the ",
      "dashed line is identity. Right, cross-validated performance against its ",
      "permutation reference. The point is the observed out-of-sample R-squared ",
      "(headline model ", facts$pred_r2, "), the thin bar is the ",
      facts$pred_interval_type, " of the repeated cross-validation companion (",
      facts$pred_repeated_r2, " ", facts$pred_repeated_interval, "), and the ",
      "grey band with its tick is the published median and 2.5-97.5% quantile ",
      "range of the permutation null (median ", facts$pred_null_median, ", ",
      facts$pred_null_interval, "). The reference is ", facts$pred_n_perm,
      " ", facts$cv_scheme, "; empirical p = ", facts$pred_perm_p,
      " for both non-null models. The dashed vertical line is the ",
      "intercept-only baseline (", facts$pred_baseline_r2, "). The repeated-CV ",
      "bar is a split-to-split resampling interval, NOT a bootstrap confidence ",
      "interval. Validation is internal - within one cohort - and is not ",
      "external validation; no causal claim is made."),
    "",
    "---",
    "",
    "## Wording that must not be changed",
    "",
    paste0("- The cross-validation grouping unit is the **animal**. Cage, ",
           "social group and batch are not grouping units; do not imply ",
           "cage- or batch-level generalisation."),
    paste0("- The repeated-CV interval is a split-to-split resampling ",
           "interval. Do not call it a bootstrap or a confidence interval."),
    paste0("- The permutation null is shown as its published quantile range ",
           "because the producing stage does not export the null draws. Do ",
           "not describe it as a null density."),
    paste0("- 'Internal validation, not external validation.' No causal ",
           "language."),
    paste0("- Panel (b) is first-active-phase, not longitudinal."),
    paste0("- Higher CombZ = more resilient-like. Do not describe CombZ as a ",
           "burden score without inverting the sign."),
    paste0("- Movement RMSSD is a supporting association only and must not be ",
           "described as an independent predictor. Entropy persistence (ACF1) ",
           "is not FDR-supported at the primary resolution and must carry ",
           "qualified wording."),
    "",
    "## Methods pointers",
    "",
    paste0("Panels (c)-(e) share one window and one animal set. Full ",
           "statistics are in `tables/manuscript/behavior_main_key_results.csv`; ",
           "per-panel plotted values are in `source_data/`; provenance is in ",
           "`manifests/`; claim-to-analysis mapping is in ",
           "`audit/behavior_main_claim_trace.csv`. GAMM temporal ",
           "characterisation of the same window is a separate Extended Data ",
           "figure produced by Stage 26 and is not restated here.")
  )
  writeLines(lines, path)
  invisible(path)
}

#' Co-author facing README for the Stage 27 output tree.
bmf_write_readme <- function(path, facts, registry_df, colours) {
  .bmf_need(facts, c("n_total", "window_definition", "validation_scheme"))
  lines <- c(
    "# Stage 27 - behavior main figure assembly",
    "",
    paste("ASSEMBLY ONLY. No model is fitted here, no p-value or q-value is",
          "computed or adjusted, no interval is estimated, no multiplicity",
          "family is redefined, and no scientific number is changed. Every",
          "value in every figure and table below is carried through from a",
          "frozen upstream canonical table."),
    "",
    "## What this stage may and may not do",
    "",
    "| May | May not |",
    "|---|---|",
    "| read canonical outputs | fit any model |",
    "| validate input schemas | recompute CombZ or redefine RES/SUS |",
    "| select manuscript-facing rows | reselect the first-night window |",
    "| format and relabel units | adjust p-values or define a family |",
    "| summarise the points it plots (median, quartiles, counts) | estimate a confidence interval |",
    "| export figures, source data, legends, manifests | recompute cross-validation |",
    "",
    paste("The prohibition is enforced from outside the script by",
          "`Testing/tests/test_behavior_main_figure_contracts.R`, which scans",
          "this stage's source for banned calls, mirroring the Stage 26",
          "precedent."),
    "",
    "## Directory layout",
    "",
    "```",
    "figures/main/                    the assembled main figure",
    "figures/panel_candidates/        individual panels and alternates",
    "figures/extended_data_candidates/ breadth/alternative panels",
    "figures/previews/                low-cost PNG previews",
    "tables/manuscript/               key results, human readable",
    "source_data/                     one file per panel + manifest",
    "legends/                         legend draft",
    "audit/                           claim trace, build record",
    "manifests/                       figure and input provenance",
    "```",
    "",
    paste("The tree is deliberately NOT resolution-scoped: a manuscript figure",
          "is not 'a 10-min analysis'. The resolution of each contributing",
          "source is recorded per input in",
          "`manifests/behavior_main_figure_input_manifest.csv` instead."),
    "",
    "## Presentation specification",
    "",
    paste0("Fixed identity colours, unchanged: CON `", colours[["CON"]],
           "`, RES `", colours[["RES"]], "`, SUS `", colours[["SUS"]], "`."),
    paste("Because RES is deliberately light, colour is never the only group",
          "encoding: point shape (circle / triangle / square) and line type",
          "(solid / long dash / dot-dash) carry the same information",
          "redundantly, which also keeps the figure readable in greyscale."),
    paste("Theme, palette, widths and export are the shared",
          "`Functions/mmm_publication_theme.R` and",
          "`Functions/gamm_publication_style_helpers.R`, so a stage figure and",
          "a manuscript figure can never disagree about group identity."),
    "Vector PDF + SVG with editable text, plus an optional PNG preview.",
    "",
    "## Reporting n",
    "",
    paste0("n = ", facts$n_total, " animals throughout panels (c) to (e). ",
           "Window: ", facts$window_definition, ". Validation scheme: ",
           facts$validation_scheme, "."),
    "",
    "## Inputs, by semantic key",
    "",
    paste("Resolved through `Functions/project_paths.R`. Moving any producer",
          "means editing that registry, not this stage."),
    "",
    "| key | role | stage | resolution |",
    "|---|---|---|---|",
    paste0("| `", registry_df$path_key, "` | ", registry_df$file_role, " | ",
           registry_df$producer_stage, " | ", registry_df$source_resolution,
           " |"),
    "",
    "## Known constraints carried from upstream",
    "",
    paste("- The CombZ component z-scoring reference and the RES/SUS threshold",
          "are defined outside this repository. See",
          "`docs/BEHAVIOR_MAIN_FIGURE_SOURCE_AUDIT.md`."),
    paste("- The domain panel is first-active-phase only, and 1 of its 30",
          "cells is FDR-supported. It shows breadth, not a signature."),
    paste("- The categorical first-night group contrast has three",
          "implementations that disagree; the declared canonical one is null,",
          "so no categorical effect is annotated."),
    paste("- The permutation null draws are not exported by the producing",
          "stage, so the null is drawn as its published quantile range."),
    paste("- Validation is internal, not external.")
  )
  writeLines(lines, path)
  invisible(path)
}
